import JSZip from 'jszip';
import { DocItem, DownloadMetrics } from '../types';
import { generateValidPdfBytes } from './pdfGenerator';

export interface ZipProgressInfo {
  percent: number;
  currentFileName: string;
  currentFileIndex: number;
  totalFiles: number;
  state: 'preparing' | 'compressing' | 'generating' | 'completed' | 'cancelled';
}

// In-memory LRU-style binary cache to eliminate redundant network downloads
const PDF_CACHE_MAX_ENTRIES = 60;
const pdfBytesCache = new Map<string, Uint8Array>();

export function getCachedPdfBytes(key: string): Uint8Array | undefined {
  return pdfBytesCache.get(key);
}

export function setCachedPdfBytes(key: string, bytes: Uint8Array): void {
  if (pdfBytesCache.size >= PDF_CACHE_MAX_ENTRIES) {
    const firstKey = pdfBytesCache.keys().next().value;
    if (firstKey) pdfBytesCache.delete(firstKey);
  }
  pdfBytesCache.set(key, bytes);
}

/**
 * Downloads a single PDF file directly from GitHub Raw CDN or generated bytes
 * Enforces a strict 20 MB hard limit on individual egress.
 */
export async function downloadSinglePdf(
  item: DocItem,
  maxBytes: number = 20 * 1024 * 1024,
  signal?: AbortSignal
): Promise<void> {
  if (item.size && item.size > maxBytes) {
    throw new Error(
      `Download blocked: ${item.name} exceeds the 20 MB egress limit (${(item.size / (1024 * 1024)).toFixed(1)} MB).`
    );
  }

  const cacheKey = item.downloadUrl || item.rawUrl || item.id;
  const cached = getCachedPdfBytes(cacheKey);

  if (cached) {
    triggerBrowserBlobDownload(cached, item.name);
    return;
  }

  // Attempt direct raw CDN fetch
  if (item.downloadUrl) {
    try {
      const resp = await fetch(item.downloadUrl, { mode: 'cors', signal });
      if (resp.ok) {
        const buf = await resp.arrayBuffer();
        if (buf.byteLength > maxBytes) {
          throw new Error(
            `Download blocked: Payload exceeds 20 MB limit (${(buf.byteLength / (1024 * 1024)).toFixed(1)} MB).`
          );
        }
        const bytes = new Uint8Array(buf);
        setCachedPdfBytes(cacheKey, bytes);
        triggerBrowserBlobDownload(bytes, item.name);
        return;
      }
    } catch (e: unknown) {
      if (e instanceof Error && e.message.includes('Download blocked')) {
        throw e;
      }
      if (signal?.aborted) throw e;
    }
  }

  // Fallback to generator
  const rawBytes = item.contentGenerator
    ? await Promise.resolve(item.contentGenerator())
    : generateValidPdfBytes({
        title: item.name.replace(/\.pdf$/i, ''),
        category: item.category || 'B.Tech Paper',
        summary: item.summary,
      });

  if (rawBytes.byteLength > maxBytes) {
    throw new Error(
      `Download blocked: Generated payload exceeds 20 MB egress limit (${(rawBytes.byteLength / (1024 * 1024)).toFixed(1)} MB).`
    );
  }

  setCachedPdfBytes(cacheKey, rawBytes);
  triggerBrowserBlobDownload(rawBytes, item.name);
}

function triggerBrowserBlobDownload(bytes: Uint8Array, fileName: string): void {
  const blob = new Blob([bytes as unknown as BlobPart], { type: 'application/pdf' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = fileName;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

/**
 * Rapidly retrieves bytes for a single DocItem with in-memory caching and abort signal
 */
async function fetchItemPdfBytes(item: DocItem, signal?: AbortSignal): Promise<Uint8Array> {
  const cacheKey = item.downloadUrl || item.rawUrl || item.id;
  const cached = getCachedPdfBytes(cacheKey);
  if (cached) return cached;

  if (item.downloadUrl) {
    try {
      const resp = await fetch(item.downloadUrl, { mode: 'cors', signal });
      if (resp.ok) {
        const buf = await resp.arrayBuffer();
        const bytes = new Uint8Array(buf);
        setCachedPdfBytes(cacheKey, bytes);
        return bytes;
      }
    } catch {
      // Fall through to contentGenerator if network is offline or blocked
    }
  }

  if (item.contentGenerator) {
    const bytes = await Promise.resolve(item.contentGenerator());
    setCachedPdfBytes(cacheKey, bytes);
    return bytes;
  }

  const generated = generateValidPdfBytes({
    title: item.name.replace(/\.pdf$/i, ''),
    category: item.category || 'B.Tech Question Paper',
    summary: item.summary,
  });
  setCachedPdfBytes(cacheKey, generated);
  return generated;
}

/**
 * Compresses up to 30 PDF files client-side into a ZIP archive with high-speed
 * concurrent downloads, in-memory caching, and optimized STORE compression.
 */
export async function createAndDownloadZip(
  files: DocItem[],
  onProgress?: (progress: ZipProgressInfo) => void,
  signal?: AbortSignal
): Promise<DownloadMetrics> {
  const startTime = performance.now();
  const cappedFiles = files.slice(0, 30);
  const totalFiles = cappedFiles.length;

  if (totalFiles === 0) {
    throw new Error('No files provided for ZIP generation');
  }

  const zip = new JSZip();
  let totalUncompressedBytes = 0;
  const fileNames: string[] = [];
  const disambiguatedNames = new Set<string>();

  onProgress?.({
    percent: 5,
    currentFileName: 'Starting parallel downloads...',
    currentFileIndex: 0,
    totalFiles,
    state: 'preparing',
  });

  // Concurrency limit: 6 simultaneous downloads matching HTTP/2 browser socket efficiency
  const CONCURRENCY_LIMIT = 6;
  let currentIndex = 0;
  let completedCount = 0;

  // Worker task that pulls from queue until all files are downloaded concurrently
  const worker = async () => {
    while (currentIndex < totalFiles) {
      if (signal?.aborted) {
        throw new DOMException('Compression cancelled by user', 'AbortError');
      }

      const index = currentIndex++;
      const file = cappedFiles[index];
      fileNames.push(file.name);

      const pdfBytes = await fetchItemPdfBytes(file, signal);
      totalUncompressedBytes += pdfBytes.byteLength;

      // Flat archive: only PDF files at the root level, no nested folders
      let targetFileName = file.name;
      let collisionCounter = 1;
      while (disambiguatedNames.has(targetFileName)) {
        const extIdx = file.name.lastIndexOf('.');
        const baseName = extIdx !== -1 ? file.name.substring(0, extIdx) : file.name;
        const ext = extIdx !== -1 ? file.name.substring(extIdx) : '.pdf';
        const disambiguator = file.semester ? ` [${file.semester}]` : file.year ? ` [${file.year}]` : ` (${collisionCounter})`;
        targetFileName = `${baseName}${disambiguator}${collisionCounter > 1 ? `-${collisionCounter}` : ''}${ext}`;
        collisionCounter++;
      }
      disambiguatedNames.add(targetFileName);

      zip.file(targetFileName, pdfBytes, { binary: true });

      completedCount++;
      const progressPercent = Math.min(85, Math.round((completedCount / totalFiles) * 80) + 5);

      onProgress?.({
        percent: progressPercent,
        currentFileName: file.name,
        currentFileIndex: completedCount,
        totalFiles,
        state: 'compressing',
      });
    }
  };

  // Launch concurrent worker pool
  const workerCount = Math.min(CONCURRENCY_LIMIT, totalFiles);
  const workers: Promise<void>[] = [];
  for (let w = 0; w < workerCount; w++) {
    workers.push(worker());
  }

  await Promise.all(workers);

  if (signal?.aborted) {
    throw new DOMException('Compression cancelled by user', 'AbortError');
  }

  // Stage 2: Generate zip blob using STORE (instantaneous for pre-compressed PDFs)
  onProgress?.({
    percent: 88,
    currentFileName: 'Packaging ZIP bundle...',
    currentFileIndex: totalFiles,
    totalFiles,
    state: 'generating',
  });

  // Using STORE compression because PDFs are already internally compressed.
  // Re-compressing with DEFLATE wastes 95% CPU time and only yields ~0.5% size difference.
  const zipBlob = await zip.generateAsync(
    {
      type: 'blob',
      compression: 'STORE',
    },
    (metadata) => {
      const compressionPercent = 88 + Math.round(metadata.percent * 0.11);
      onProgress?.({
        percent: Math.min(99, compressionPercent),
        currentFileName: metadata.currentFile ? `Finalizing ${metadata.currentFile}` : 'Building archive...',
        currentFileIndex: totalFiles,
        totalFiles,
        state: 'generating',
      });
    }
  );

  const durationMs = Math.round(performance.now() - startTime);
  const totalCompressedBytes = zipBlob.size;

  // Format date stamp for filename: YYYYMMDD-HHMM
  const now = new Date();
  const dateStr = now.toISOString().slice(0, 10).replace(/-/g, '');
  const timeStr = `${String(now.getHours()).padStart(2, '0')}${String(now.getMinutes()).padStart(2, '0')}`;
  const archiveName = `btechpapers-bundle-${dateStr}-${timeStr}.zip`;

  if (signal?.aborted) {
    throw new DOMException('Compression cancelled by user', 'AbortError');
  }

  // Trigger download
  const downloadUrl = URL.createObjectURL(zipBlob);
  const downloadLink = document.createElement('a');
  downloadLink.href = downloadUrl;
  downloadLink.download = archiveName;
  document.body.appendChild(downloadLink);
  downloadLink.click();
  document.body.removeChild(downloadLink);
  setTimeout(() => URL.revokeObjectURL(downloadUrl), 1000);

  const uncompressedMb = (totalUncompressedBytes / (1024 * 1024)).toFixed(2);
  const compressedMb = (totalCompressedBytes / (1024 * 1024)).toFixed(2);
  const ratioPercent =
    totalUncompressedBytes > 0
      ? `${Math.max(0, Math.round((1 - totalCompressedBytes / totalUncompressedBytes) * 100))}%`
      : '0%';

  const speedMBps =
    durationMs > 0
      ? ((totalUncompressedBytes / (1024 * 1024)) / (durationMs / 1000)).toFixed(2)
      : '0.00';

  const metrics: DownloadMetrics = {
    archiveName,
    fileCount: totalFiles,
    fileNames,
    uncompressedBytes: totalUncompressedBytes,
    compressedBytes: totalCompressedBytes,
    uncompressedMb,
    compressedMb,
    compressionRatio: ratioPercent,
    durationMs,
    speedMBps,
  };

  onProgress?.({
    percent: 100,
    currentFileName: 'Download complete!',
    currentFileIndex: totalFiles,
    totalFiles,
    state: 'completed',
  });

  return metrics;
}
